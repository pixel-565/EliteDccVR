inline bool shipFingerprint(const void *data, SIZE_T size, const unsigned char *expected)
{
    if(!data || size>1048576)return false;
    unsigned char hash[32];
    return BCryptHash(BCRYPT_SHA256_ALG_HANDLE,nullptr,0,(PUCHAR)data,static_cast<ULONG>(size),hash,32)==0 && !memcmp(hash,expected,32);
}
inline bool shipShader(const void *data,SIZE_T size)
{
    static constexpr unsigned char expected[]={0x0c,0x59,0x84,0xb4,0xaa,0xb7,0x6e,0x9b,0xf0,0x65,0x19,0xc5,0x74,0x20,0x5f,0x19,0xcf,0xd0,0x42,0x41,0x9a,0x07,0xb9,0x1d,0x52,0xa8,0xcb,0x85,0x5b,0xfc,0x25,0xb9};
    return shipFingerprint(data,size,expected);
}
inline bool shipGeometry(const void *data,SIZE_T size)
{
    static constexpr unsigned char expected[]={0x93,0xb4,0x79,0x61,0x57,0x8c,0xa9,0xae,0xcd,0x73,0xb0,0x9f,0x41,0xa5,0x71,0x66,0x98,0xb7,0x04,0x80,0x50,0xee,0xf7,0xa9,0x3e,0xbd,0x70,0xda,0xd6,0x97,0x27,0x29};
    return size==160 && shipFingerprint(data,size,expected);
}
